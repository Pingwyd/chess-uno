/** Material + piece-square evaluation from `color`'s perspective. */
export function evaluate(board: string[], color: Color): number {
  let white = 0, black = 0, nonPawn = 0;
  for (let sq = 0; sq < 64; sq++) {
    const p = board[sq];
    if (p && p !== 'K' && p !== 'k' && p !== 'P' && p !== 'p') nonPawn += VALUE[p.toLowerCase()];
  }
  const endgame = nonPawn <= 1800;
  for (let sq = 0; sq < 64; sq++) {
    const p = board[sq];
    if (!p) continue;
    const isWhite = p < 'a';
    const t = isWhite ? p.toLowerCase() : p;
    const idx = isWhite ? (7 - rankOf(sq)) * 8 + fileOf(sq) : rankOf(sq) * 8 + fileOf(sq);
    const table = t === 'k' && endgame ? PST.ke : PST[t];
    const v = VALUE[t] + table[idx];
    if (isWhite) white += v; else black += v;
  }
  const score = white - black;
  return color === 'w' ? score : -score;
}
